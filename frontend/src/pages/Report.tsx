import { useEffect, useState } from "react";
import { api } from "../api";
import { Markdown } from "../components/Markdown";
import { ErrorBox, Loading, Panel } from "../components/ui";

export function Report() {
  const [md, setMd] = useState<string | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [missing, setMissing] = useState(false);
  useEffect(() => {
    api.latestBenchmarkReport().then(setMd).catch((e) => (e.status === 404 ? setMissing(true) : setErr(e.message)));
  }, []);
  if (err) return <ErrorBox message={err} />;
  if (missing)
    return (
      <Panel title="Research report">
        <p className="muted">No completed benchmark exists yet, so no report can be generated. Run <code>python -m gauntlet bench</code>.
          A per-run report is available on each run's page under the <em>Research report</em> tab.</p>
      </Panel>
    );
  if (!md) return <Loading what="Generating report" />;
  return (
    <Panel title="Research report (latest benchmark)" sub="Generated by the backend from recorded benchmark data."
      actions={<a className="btn" href={`data:text/markdown;charset=utf-8,${encodeURIComponent(md)}`} download="gauntlet-benchmark-report.md">Download .md</a>}>
      <Markdown source={md} />
    </Panel>
  );
}
